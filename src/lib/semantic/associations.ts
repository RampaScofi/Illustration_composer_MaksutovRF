/**
 * Находит концепты, затронутые основами слов запроса.
 * Сравнение идёт по стеммированным формам триггеров.
 */
export function findConcepts(
  stems: readonly string[],
  stem: (word: string) => string,
): AssociationConcept[] {
  const matched: AssociationConcept[] = [];

  for (const concept of ASSOCIATIONS) {
    const triggers = concept.triggers.map(stem);
    if (stems.some((s) => triggers.some((t) => t === s || s.startsWith(t) || t.startsWith(s)))) {
      matched.push(concept);
    }
  }

  return matched;
}
